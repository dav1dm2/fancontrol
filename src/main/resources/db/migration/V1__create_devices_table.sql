CREATE TABLE devices (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fan_state boolean NOT NULL,
    last_sensor_activation timestamp(6) without time zone,
    name varchar(255) NOT NULL,
    status varchar(255) NOT NULL,
    last_seen timestamp(6) without time zone,
    CONSTRAINT devices_pkey PRIMARY KEY (id),
    CONSTRAINT devices_name_key UNIQUE (name),
    CONSTRAINT devices_status_check CHECK (status IN ('ONLINE', 'OFFLINE'))
);
